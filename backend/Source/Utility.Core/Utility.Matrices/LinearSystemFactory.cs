	public static (SparseMatrix<double> Matrix, double[] Rhs, double[] Solution) ManufacturedDiffusion(int gridSize, ManufacturedDiffusionCase diffusionCase)
	{
		if (gridSize < 2)
		{
			throw new ArgumentOutOfRangeException("gridSize");
		}
		int count = gridSize * gridSize;
		int[] manufacturedDiffusionRowPointers = BuildManufacturedDiffusionRowPointers(gridSize);
		int[] columnIndices = new int[manufacturedDiffusionRowPointers[count]];
		double[] values = new double[manufacturedDiffusionRowPointers[count]];
		double[] doubleValues = new double[count];
		FillManufacturedDiffusionMatrix(gridSize, diffusionCase, columnIndices, values, doubleValues);
		SparseMatrix<double> sparseMatrix = new SparseMatrix<double>(count, manufacturedDiffusionRowPointers, columnIndices, values);
		return (Matrix: sparseMatrix, Rhs: DeriveRhs(sparseMatrix, doubleValues), Solution: doubleValues);
	}

	private static int[] BuildManufacturedDiffusionRowPointers(int gridSize)
	{
		int[] manufacturedDiffusionRowPointers = new int[gridSize * gridSize + 1];
		for (int i = 0; i < gridSize; i++)
		{
			for (int j = 0; j < gridSize; j++)
			{
				int unity = 1;
				if (i > 0)
				{
					unity++;
				}
				if (i < gridSize - 1)
				{
					unity++;
				}
				if (j > 0)
				{
					unity++;
				}
				if (j < gridSize - 1)
				{
					unity++;
				}
				int gridSizeTerm = i * gridSize + j;
				manufacturedDiffusionRowPointers[gridSizeTerm + 1] = manufacturedDiffusionRowPointers[gridSizeTerm] + unity;
			}
		}
		return manufacturedDiffusionRowPointers;
	}

	private static void FillManufacturedDiffusionMatrix(int gridSize, ManufacturedDiffusionCase diffusionCase, int[] columnIndices, double[] values, double[] solution)
	{
		int ordinal = 0;
		for (int i = 0; i < gridSize; i++)
		{
			for (int j = 0; j < gridSize; j++)
			{
				int columnIndices2 = i * gridSize + j;
				double manufacturedHorizontalWeight = ManufacturedHorizontalWeight(i, j, gridSize, diffusionCase);
				double manufacturedHorizontalWeight2 = ManufacturedHorizontalWeight(i, j + 1, gridSize, diffusionCase);
				double manufacturedVerticalWeight = ManufacturedVerticalWeight(i, j, gridSize, diffusionCase);
				double manufacturedVerticalWeight2 = ManufacturedVerticalWeight(i + 1, j, gridSize, diffusionCase);
				if (i > 0)
				{
					columnIndices[ordinal] = columnIndices2 - gridSize;
					values[ordinal++] = 0.0 - manufacturedVerticalWeight;
				}
				if (j > 0)
				{
					columnIndices[ordinal] = columnIndices2 - 1;
					values[ordinal++] = 0.0 - manufacturedHorizontalWeight;
				}
				columnIndices[ordinal] = columnIndices2;
				values[ordinal++] = manufacturedHorizontalWeight + manufacturedHorizontalWeight2 + manufacturedVerticalWeight + manufacturedVerticalWeight2;
				if (j < gridSize - 1)
				{
					columnIndices[ordinal] = columnIndices2 + 1;
					values[ordinal++] = 0.0 - manufacturedHorizontalWeight2;
				}
				if (i < gridSize - 1)
				{
					columnIndices[ordinal] = columnIndices2 + gridSize;
					values[ordinal++] = 0.0 - manufacturedVerticalWeight2;
				}
				double gridSizeTerm = ((double)j + 1.0) / ((double)gridSize + 1.0);
				double gridSizeTerm2 = ((double)i + 1.0) / ((double)gridSize + 1.0);
				solution[columnIndices2] = Math.Sin(Math.PI * gridSizeTerm) * Math.Sin(Math.PI * 2.0 * gridSizeTerm2) + 0.25 * Math.Sin(Math.PI * 3.0 * gridSizeTerm) * Math.Sin(Math.PI * gridSizeTerm2);
			}
		}
	}

	private static double ManufacturedHorizontalWeight(int row, int faceColumn, int gridSize, ManufacturedDiffusionCase diffusionCase)
	{
		if (diffusionCase == ManufacturedDiffusionCase.Constant)
		{
			return 1.0;
		}
		double rowOffsetOverGridSizeOffset = ((double)row + 1.0) / ((double)gridSize + 1.0);
		double faceColumnOverGridSize = (double)faceColumn / (double)gridSize;
		return 1.0 + 0.45 * Math.Sin(Math.PI * 2.0 * rowOffsetOverGridSizeOffset) * Math.Cos(Math.PI * faceColumnOverGridSize);
	}

	private static double ManufacturedVerticalWeight(int faceRow, int column, int gridSize, ManufacturedDiffusionCase diffusionCase)
	{
		if (diffusionCase == ManufacturedDiffusionCase.Constant)
		{
			return 1.0;
		}
		double faceRowOverGridSize = (double)faceRow / (double)gridSize;
		double columnOffsetOverGridSizeOffset = ((double)column + 1.0) / ((double)gridSize + 1.0);
		return 25.0 * (1.0 + 0.45 * Math.Cos(Math.PI * 2.0 * columnOffsetOverGridSizeOffset) * Math.Sin(Math.PI * faceRowOverGridSize));
	}

	public static (SparseMatrix<double> Matrix, double[] Rhs, double[] Solution) BlockDiagonal(params (SparseMatrix<double> Matrix, double[] Rhs, double[] Solution)[] blocks)
	{
		int rowCountSum = 0;
		for (int i = 0; i < blocks.Length; i++)
		{
			rowCountSum += blocks[i].Matrix.RowCount;
		}
		double[,] doubleValues = new double[rowCountSum, rowCountSum];
		double[] doubleValuesArray = new double[rowCountSum];
		double[] doubleValues2 = new double[rowCountSum];
		int rowCountSum2 = 0;
		for (int j = 0; j < blocks.Length; j++)
		{
			SparseMatrix<double> matrix = blocks[j].Matrix;
			int rowCount = matrix.RowCount;
			for (int k = 0; k < rowCount; k++)
			{
				for (int l = matrix.RowPointers[k]; l < matrix.RowPointers[k + 1]; l++)
				{
					doubleValues[rowCountSum2 + k, rowCountSum2 + matrix.ColumnIndices[l]] = matrix.Values[l];
				}
				doubleValuesArray[rowCountSum2 + k] = blocks[j].Rhs[k];
				doubleValues2[rowCountSum2 + k] = blocks[j].Solution[k];
			}
			rowCountSum2 += rowCount;
		}
		return (Matrix: new SparseMatrix<double>(doubleValues), Rhs: doubleValuesArray, Solution: doubleValues2);
	}

