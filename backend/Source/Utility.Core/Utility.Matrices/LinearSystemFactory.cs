		double[] vectorArray = LinearSystemIO.ReadVector(stemPath + ".sol");
		return (Matrix: matrix, Rhs: vector, Solution: vectorArray);
	}

	public static bool TryLoad(string stemPath, out (SparseMatrix<double> Matrix, double[] Rhs, double[] Solution) system)
	{
		if (!File.Exists(stemPath + ".matrix"))
		{
			system = default;
			return false;
		}
		system = Load(stemPath);
		return true;
	}

	public static (SparseMatrix<double> Matrix, double[] Rhs, double[] Solution) LoadHydraulic(string name)
	{
		return Load(Path.Combine("C:\\Temp\\RAS\\LinearSystems", name));
	}

	private static double[] DeriveRhs(SparseMatrix<double> matrix, double[] solution)
	{
		double[] doubleValues = new double[matrix.RowCount];
		SparseMatrix<double>.Product(matrix, solution, doubleValues);
		return doubleValues;
	}
